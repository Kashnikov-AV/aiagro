def check_model_availability():
    """Проверяет наличие обученной модели YOLO"""
    if not WEED_MODEL_PATH.exists():
        print(f"⚠️ ПРЕДУПРЕЖДЕНИЕ: Модель YOLO не найдена по пути: {WEED_MODEL_PATH}")
        print(f"   Пожалуйста, обучите модель используя ml/train_weed_detector.ipynb")
        print(f"   или скачайте готовую модель и сохраните её в {ML_MODELS_DIR}")
        return False
    else:
        model_size_mb = WEED_MODEL_PATH.stat().st_size / 1024 / 1024
        print(f"✅ Модель YOLO найдена: {WEED_MODEL_PATH.name} ({model_size_mb:.2f} MB)")
        return True


